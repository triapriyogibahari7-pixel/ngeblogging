import {execFileSync} from 'node:child_process';
import {mkdtemp,readFile,writeFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {gzipSync} from 'node:zlib';
import {createHash} from 'node:crypto';
import {OFFLINE_TESTS,commerceTapEvidence} from './domain-commerce-cloudflare-build.mjs';
const branch='feat/domain-commerce-cloudflare-prod-20261102',version='4.156.0',root=process.cwd();
let work;
try{
 if(process.env.WORKERS_CI!=='1'||process.env.WORKERS_CI_BRANCH!==branch)throw Error('REPAIR_REQUIRES_CLOUDFLARE_COMMERCE_BRANCH');
 const git=args=>execFileSync('git',args,{cwd:root,encoding:'utf8',timeout:30000}).trim();
 const commit=git(['rev-parse','HEAD']);
 if(commit!==process.env.WORKERS_CI_COMMIT_SHA)throw Error('REPAIR_COMMIT_MISMATCH');
 work=await mkdtemp(join(tmpdir(),'commerce-lock-repair-'));
 const archive=join(work,'source.tar');
 execFileSync('git',['archive','--format=tar','--output='+archive,commit],{cwd:root,timeout:30000});
 execFileSync('tar',['-xf',archive,'-C',work],{timeout:30000});
 await rm(join(work,'.npmrc'),{force:true});
 const env={PATH:process.env.PATH||'',HOME:work,TMPDIR:work,CI:'true',NODE_ENV:'test',WRANGLER_SEND_METRICS:'false',LANG:'C.UTF-8',NPM_CONFIG_USERCONFIG:'/dev/null',NPM_CONFIG_GLOBALCONFIG:'/dev/null'};
 const run=(cmd,args)=>execFileSync(cmd,args,{cwd:work,env,encoding:'utf8',timeout:180000,maxBuffer:8*1024*1024,stdio:['ignore','pipe','pipe']});
 const actual=run('npm',['view','wrangler@'+version,'version','--registry=https://registry.npmjs.org']).trim();
 if(actual!==version)throw Error('REPAIR_CANDIDATE_NOT_VERIFIED');
 run('npm',['install','--save-dev','--save-exact','--package-lock-only','--ignore-scripts','--no-audit','--no-fund','--registry=https://registry.npmjs.org','wrangler@'+version]);
 run('npm',['ci','--no-audit','--no-fund','--registry=https://registry.npmjs.org']);
 run(process.execPath,['--input-type=module','-e',"import * as w from 'wrangler'; if(typeof w.createTestHarness!=='function')throw Error('TEST_HARNESS_UNAVAILABLE');"]);
 const config=JSON.parse(await readFile(join(work,'wrangler.production.jsonc'),'utf8'));
 const nativeSource=await readFile(join(work,'tests/domain-auth-native-runtime.test.mjs'),'utf8');
 if(config.compatibility_date!=='2026-07-30'||!nativeSource.includes("compatibility_date:'2026-07-30'"))throw Error('REPAIR_COMPATIBILITY_DATE_CHANGED');
 const offline=commerceTapEvidence(run(process.execPath,['--test','--test-reporter=tap',...OFFLINE_TESTS]),41);
 const native=commerceTapEvidence(run(process.execPath,['--test','--test-reporter=tap','tests/domain-auth-native-runtime.test.mjs']),9);
 const files={};
 for(const path of ['package.json','package-lock.json'])files[path]=await readFile(join(work,path),'utf8');
 const manifest=JSON.parse(files['package.json']),lock=JSON.parse(files['package-lock.json']);
 if(manifest.devDependencies?.wrangler!==version||lock.packages?.['']?.devDependencies?.wrangler!==version||lock.packages?.['node_modules/wrangler']?.version!==version)throw Error('REPAIR_MANIFEST_LOCK_MISMATCH');
 const tree=JSON.parse(run('npm',['ls','wrangler','miniflare','workerd','--json']));
 const bundle=JSON.stringify({schemaVersion:1,sourceCommit:commit,wrangler:version,compatibilityDate:config.compatibility_date,validation:{offline,native},tree,files});
 const packed=gzipSync(Buffer.from(bundle)).toString('base64');
 console.log('COMMERCE_REPAIR_BUNDLE_BEGIN '+JSON.stringify({sourceCommit:commit,sha256:createHash('sha256').update(bundle).digest('hex'),encoding:'gzip+base64',characters:packed.length}));
 for(let i=0;i<packed.length;i+=3000)console.log('COMMERCE_REPAIR_CHUNK '+i+' '+packed.slice(i,i+3000));
 console.log('COMMERCE_REPAIR_BUNDLE_END');
 console.log('MAINTENANCE_ONLY: candidate manifests require review and a separate commit. No deployment or release proof was produced.');
 process.exitCode=78;
}catch(error){
 const message=String(error?.message||'REPAIR_FAILED').split('\n')[0].slice(0,500);
 console.error('COMMERCE_REPAIR_FAILED '+message);
 for(const field of ['stdout','stderr'])if(error?.[field])console.error(String(error[field]).slice(-20000).replace(/Bearer\s+[^\s"']+/gi,'Bearer [REDACTED]').replace(/(?:sb_secret_|github_pat_|ghp_)[A-Za-z0-9_-]+/g,'[REDACTED]'));
 process.exitCode=1;
}finally{if(work)await rm(work,{recursive:true,force:true});}
