import test from 'node:test';
import assert from 'node:assert/strict';
import {purchaseSelectionError} from '../src/domain-purchase-selection.mjs';
const quote={quoteId:'quote-a',domain:'example.com',expiresAt:'2030-01-01T00:00:00Z'};
const now=Date.parse('2029-01-01T00:00:00Z');
const normalizeDomain=value=>{if(typeof value!=='string'||!value.trim()||value.includes('/'))throw Error();return value.trim().toLowerCase();};
const check=overrides=>purchaseSelectionError({quote,input:'example.com',normalizeDomain,now,...overrides});
test('matching domain with fresh quote is accepted',()=>assert.equal(check({}),null));
test('canonicalized input is accepted',()=>assert.equal(check({input:' EXAMPLE.COM '}),null));
test('changed domain is rejected',()=>assert.equal(check({input:'other.com'}),'QUOTE_SELECTION_CHANGED'));
test('invalid input is rejected',()=>assert.equal(check({input:'https://example.com'}),'INVALID_DOMAIN'));
test('expired quote is rejected',()=>assert.equal(check({now:Date.parse(quote.expiresAt)}),'QUOTE_EXPIRED'));
test('invalid expiration is rejected',()=>assert.equal(check({quote:{...quote,expiresAt:'invalid'}}),'QUOTE_EXPIRED'));
test('invalid clock is rejected',()=>assert.equal(check({now:NaN}),'QUOTE_EXPIRED'));
test('missing quote is rejected',()=>assert.equal(check({quote:null}),'QUOTE_UNVERIFIED'));
test('saved order can resume the same quote after expiration',()=>assert.equal(check({input:'',now:Date.parse('2031-01-01T00:00:00Z'),attempt:{phase:'order',quote}}),null));
test('different saved quote is held',()=>assert.equal(check({attempt:{phase:'order',quote:{...quote,quoteId:'quote-b'}}}),'ATTEMPT_HELD'));
test('different saved domain is held',()=>assert.equal(check({attempt:{phase:'order',quote:{...quote,domain:'other.com'}}}),'ATTEMPT_HELD'));
for(const phase of ['checkout','review','checkout_ready'])test('saved '+phase+' cannot create a new checkout',()=>assert.equal(check({attempt:{phase,quote}}),'ATTEMPT_HELD'));
