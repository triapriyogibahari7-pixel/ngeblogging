// UI-only guard. Server-side subscription authorization remains unchanged.
export function isActiveNaraProButton(button) {
  return Boolean(button?.matches?.('.nara-context-bar > button')) &&
    String(button.textContent || '').replace(/\s+/g, ' ').trim() === 'Pro aktif';
}

function preventActiveProUpgrade(event) {
  const target = event.target instanceof Element ? event.target : event.target?.parentElement;
  const button = target?.closest('.nara-context-bar > button');
  if (!isActiveNaraProButton(button)) return;
  event.preventDefault();
  event.stopImmediatePropagation();
}

// One delegated listener, including clicks generated by keyboard activation.
if (typeof document !== 'undefined') {
  document.addEventListener('click', preventActiveProUpgrade, true);
}

if (import.meta.hot) {
  import.meta.hot.dispose(() => {
    document.removeEventListener('click', preventActiveProUpgrade, true);
  });
}
